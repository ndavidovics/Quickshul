<p>We implement industry-standard technical and organizational measures to protect your data, including:</p>
<ul>
    <li>TLS/HTTPS encryption for all data in transit</li>
    <li>Bcrypt hashing for stored passwords</li>
    <li>Access controls limiting data access to authorized YIOM staff only</li>
    <li>Regular security reviews of the Portal infrastructure</li>
</ul>
