<p>We do <strong>not</strong> sell, rent, or trade your personal information. We may share information only in these limited circumstances:</p>
<ul>
    <li><strong>Service providers:</strong> Trusted vendors (such as our hosting provider and Intuit QuickBooks) who process data on our behalf under confidentiality obligations</li>
    <li><strong>Legal compliance:</strong> When required by law, court order, or governmental authority</li>
    <li><strong>Safety:</strong> To protect the rights, property, or safety of YIOM, our members, or others</li>
    <li><strong>With your consent:</strong> In any other circumstances with your explicit agreement</li>
</ul>

