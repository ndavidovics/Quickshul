<p>Young Israel of Memphis ("<strong>YIOM</strong>", "we", "us", or "our") is committed to protecting the privacy of our members. This Privacy Policy describes how we collect, use, store, share, and protect your personal information when you use the Member Portal at <strong>portal.yiom.org</strong> ("<strong>Portal</strong>").</p>

<p>By using the Portal, you consent to the data practices described in this Policy. If you do not agree, please discontinue use of the Portal and contact the synagogue office to manage your information directly.</p>

<h2>1. Information We Collect</h2>
<p>We collect information in the following ways:</p>

<p><strong>Information you provide directly:</strong></p>
<ul>
    <li>Name, email address, and contact details when you register or update your profile</li>
    <li>Password (stored in encrypted, hashed form — we never store plain-text passwords)</li>
    <li>Correspondence or requests submitted through the Portal</li>
</ul>

<p><strong>Information from third-party sign-in:</strong></p>
<ul>
    <li>If you sign in with <strong>Google</strong>, we receive your name, email address, and Google profile picture from Google LLC. We do not receive your Google password. Google's use of your data is governed by <a href="https://policies.google.com/privacy" target="_blank" rel="noopener">Google's Privacy Policy</a>.</li>
</ul>

<p><strong>Financial information from QuickBooks:</strong></p>
<ul>
    <li>Membership dues balances and payment history</li>
    <li>Charitable donation records and acknowledgment data</li>
    <li>Account standing and billing information as maintained in YIOM's QuickBooks Online account</li>
</ul>
<p>This financial data is retrieved from <strong>Intuit QuickBooks Online</strong> and displayed within the Portal. We do not store your payment card numbers, bank account numbers, or other sensitive payment credentials.</p>

<p><strong>Automatically collected information:</strong></p>
<ul>
    <li>IP address and browser/device type (for security logging and session management)</li>
    <li>Pages visited and actions taken within the Portal (for troubleshooting and improvement)</li>
    <li>Session cookies necessary for authentication</li>
</ul>

<h2>2. How We Use Your Information</h2>
<p>We use your information only for legitimate purposes related to your membership:</p>
<ul>
    <li>To authenticate your identity and provide secure access to your account</li>
    <li>To display your membership information, dues history, and donation records</li>
    <li>To communicate with you about your membership, account, or synagogue matters</li>
    <li>To process and record membership transactions through QuickBooks</li>
    <li>To maintain the security and integrity of the Portal</li>
    <li>To comply with legal obligations, including tax-related donation acknowledgments</li>
    <li>To improve Portal functionality based on usage patterns</li>
</ul>

<h2>3. QuickBooks Integration and Financial Data</h2>
<p>The Portal integrates with <strong>Intuit QuickBooks Online</strong> to provide you with real-time access to your financial membership records. In connection with this integration:</p>
<ul>
    <li>YIOM accesses your financial records stored in its QuickBooks account through the Intuit API</li>
    <li>Data is transmitted over encrypted (TLS/HTTPS) connections</li>
    <li>YIOM does not share your personal financial data with Intuit beyond what is inherent to using the QuickBooks platform as our accounting system</li>
    <li>Intuit's handling of data processed through QuickBooks is governed by <a href="https://www.intuit.com/privacy/statement/" target="_blank" rel="noopener">Intuit's Global Privacy Statement</a></li>
</ul>

<h2>4. Cookies and Session Data</h2>
<p>The Portal uses <strong>strictly necessary cookies</strong> to maintain your login session. These cookies are:</p>
<ul>
    <li>Not used for advertising or cross-site tracking</li>
    <li>Deleted when you log out or when your session expires</li>
    <li>"Remember me" cookies, if selected, are stored for up to 30 days</li>
</ul>
<p>We do not use third-party advertising cookies or analytics platforms that track you across other websites.</p>

